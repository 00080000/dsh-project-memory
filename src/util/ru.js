/**
 * 在 `w` 的词尾里找最长匹配，且词尾起点 ≥ `region`（Snowball 的 region 约束）。
 * @returns {{start: number, group: number}|null} start = 词尾起点下标
 */
function among(w, table, region = 0) {
  for (const [suffix, group] of table) {
    if (w.endsWith(suffix)) {
      const start = w.length - suffix.length
      if (start >= region) return { start, group }
      // 更长的词尾越界了不代表更短的也越界（短词尾起点更靠后）：继续往下找最长**合法**匹配。
    }
  }
  return null
}

/**
 * Snowball Russian 的 RV / R2（严格照 snowballstemmer 的 mark_regions 逐句对应）。
 * RV = 第一个元音之后；R2 = RV 之后再经历一次"元音→非元音"的边界之后。
 */
function markRegions(w) {
  const n = w.length
  const isV = (i) => i >= 0 && i < n && VOWELS.has(w[i])
  let pV = n
  let p2 = n
  let i = 0
  while (i < n && !isV(i)) i++
  if (i >= n) return { pV, p2 }
  pV = i + 1
  i = pV
  while (isV(i)) i++
  if (i >= n) return { pV, p2 }
  i += 1
  while (i < n && !isV(i)) i++
  if (i >= n) return { pV, p2 }
  i += 1
  while (isV(i)) i++
  if (i >= n) return { pV, p2 }
  p2 = i + 1
  return { pV, p2 }
}

/** group 1 的附加条件：紧邻词尾的前一个字符是 а/я，且该字符也在 RV 内。 */
function vowelBefore(w, start, rv) {
  const ch = w[start - 1]
  return (ch === 'а' || ch === 'я') && start - 1 >= rv
}

// Step 1 的分组与顺序照参考实现：副动词 → 反身 → 形容词（可叠分词尾）→ 动词 → 名词。
// 注意三类 group 1 的语义完全一致：**只要求**前接 а/я，删除的仍只是词尾本身。
function step1(w, rv) {
  const g = among(w, GERUND, rv)
  if (g && (g.group === 2 || vowelBefore(w, g.start, rv))) return w.slice(0, g.start)
  const r = among(w, REFLEXIVE, rv)
  if (r) w = w.slice(0, r.start)
  const a = among(w, ADJECTIVE, rv)
  if (a) {
    const stem = w.slice(0, a.start)
    const p = among(stem, PARTICIPLE, rv)
    if (p && (p.group === 2 || vowelBefore(stem, p.start, rv))) return stem.slice(0, p.start)
    return stem // 分词尾条件不满足：形容词尾已删，分词尾保留
  }
  const v = among(w, VERB, rv)
  if (v && (v.group === 2 || vowelBefore(w, v.start, rv))) return w.slice(0, v.start)
  const n = among(w, NOUN, rv)
  if (n) return w.slice(0, n.start)
  return w
}

/**
 * 俄语词干（Snowball Russian，逐句移植 snowballstemmer 3.1.1 的实现）。
 *
 * 为什么不用"剥后缀表"：那类实现没有 RV/R2 约束、也不区分 group 前置条件，
 * 越短的词越容易误合并。移植版用 8,354 个词形（2,354 个生成词形 + 6,000 个随机串）
 * 与参考实现做了逐词一致性对照（0 处不一致），覆盖 RV/R2 边界、group 前置条件、tidy 的 н 处理。
 *
 * @param {string} word 已 lowercase 的词（ё 会在这里归一成 е）
 * @returns {string}
 */
export function stemRu(word) {
  let w = String(word || '').toLowerCase().replace(/ё/g, 'е')
  if (!w || !CYRILLIC_RANGE.test(w)) return w
  const { pV, p2 } = markRegions(w)
  w = step1(w, pV)
  // Step 2：词尾 и（必须在 RV 内）
  if (w.endsWith('и') && w.length - 1 >= pV) w = w.slice(0, -1)
  // Step 3：派生后缀 ость / ост（起点必须在 R2 内）
  const d = among(w, DERIVATIONAL, p2)
  if (d) w = w.slice(0, d.start)
  // Step 4：最高级 / нн→н / 去软音符号。
  // 注意参考实现的 slice_del 只删"词尾本身"：нн→н 是删掉一个 н，不是两个。
  const t = among(w, TIDY, pV) // 参考实现的 tidy 仍受 RV 约束（limit_backward 未复原）
  if (t) {
    if (t.group === 3) {
      w = w.slice(0, t.start) // ь
    } else if (t.group === 2) {
      if (w[t.start - 1] === 'н') w = w.slice(0, t.start) // 前一个是 н 才删这个 н
    } else {
      w = w.slice(0, t.start) // ейше/ейш
      if (w.endsWith('нн')) w = w.slice(0, -1) // 后面是 нн 时再削一个 н
    }
  }
  return w
}

/** ё 归一成 е（同一个词的两种拼写/输入法应当命中）。 */
export function normalizeRuWord(word) {
  return String(word || '').toLowerCase().replace(/ё/g, 'е')
}
